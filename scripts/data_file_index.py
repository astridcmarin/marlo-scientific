"""Writes docs/DATA_FILES.md: every pinned JSON data file, grouped by family, with the current version marked.

A family is a file name without its version suffix (_v3, _v1_1). The table shows the latest version and the earlier
ones. Earlier is not the same as unused: a locked plan or a check report keeps citing the version it was made with (the
body map, for example, shows time course v1 under plan v1). Files are not moved, because their paths are part of the pins. Run: python3 scripts/data_file_index.py  (a test checks the output is current).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIRS = ('intelligence_store/data', 'landscape_ui/data')
OUT = ROOT / 'docs' / 'DATA_FILES.md'
VERSION = re.compile(r'^(?P<family>.+?)_v(?P<major>\d+)(?:_(?P<minor>\d+))?$')


def families():
    fams = {}
    for d in DIRS:
        for f in sorted((ROOT / d).rglob('*.json')):
            rel = f.relative_to(ROOT).as_posix()
            if '/curation/' in rel:
                continue
            m = VERSION.match(f.stem)
            key = (f.parent.relative_to(ROOT).as_posix(), m.group('family') if m else f.stem)
            ver = (int(m.group('major')), int(m.group('minor') or 0)) if m else (0, 0)
            fams.setdefault(key, []).append((ver, rel))
    return {k: sorted(v) for k, v in sorted(fams.items())}


def render():
    fams = families()
    total = sum(len(v) for v in fams.values())
    superseded = sum(len(v) - 1 for v in fams.values())
    lines = ['# Data files', '',
             'Generated by `scripts/data_file_index.py`; do not edit by hand (a test checks it is current).', '',
             f'{total} JSON data files in {len(fams)} families; {superseded} are earlier versions. A family is a file name without its '
             'version suffix. Earlier versions stay in place and unchanged: records, plans and reports made with them cite them by '
             'checksum, some are still in use for that reason (a locked plan keeps its own version), and moving them would change '
             'their pinned paths. Which version a module uses is set by the checksum constant in that module.', '']
    folder = None
    for (d, fam), versions in fams.items():
        if d != folder:
            lines += ['', f'## `{d}/`', '', '| Family | Latest | Earlier versions |', '|---|---|---|']
            folder = d
        current = versions[-1][1].rsplit('/', 1)[-1]
        old = ', '.join(v[1].rsplit('/', 1)[-1] for v in versions[:-1]) or '—'
        lines.append(f'| {fam} | `{current}` | {old} |')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    OUT.write_text(render())
    print(f'wrote {OUT.relative_to(ROOT)}')
