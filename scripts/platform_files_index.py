"""Write docs/PLATFORM_FILES.md: every file tracked by git, by area, with a one-line description read from the file.

The description is taken from the file itself, never written by hand: a Python module's docstring, a document's
first heading, a JSON file's schema and title or purpose, an HTML template's title or first heading. A file with
none of these is listed with its type only. tests/test_platform_files_index.py checks the index is current.

    python3 scripts/platform_files_index.py
"""
import ast
import json
import re
import subprocess
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'docs' / 'PLATFORM_FILES.md'
AREAS = OrderedDict([
    ('(root)', 'Repository root'),
    ('.github', 'Continuous integration'),
    ('app', 'Flask application entry point and its pages'),
    ('landscape_ui', 'Research workspace: page modules, templates, styles and scripts'),
    ('intelligence_store', 'Scientific code, knowledge modules and pinned data'),
    ('intelligence_migrations', 'Database migrations (Alembic)'),
    ('scripts', 'Command-line utilities and build scripts'),
    ('tests', 'Automated tests'),
    ('examples', 'Synthetic examples'),
    ('docs', 'Documentation'),
])
MAX = 160


def tracked_files():
    out = subprocess.run(['git', 'ls-files'], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return sorted(p for p in out.split('\n') if p)


def _short(text):
    text = re.sub(r'\s+', ' ', text or '').strip()
    first = re.split(r'(?<=[.!?])\s', text, maxsplit=1)[0]
    return (first[:MAX - 1] + '…') if len(first) > MAX else first


def describe(path):
    p = ROOT / path
    suffix = p.suffix.lower()
    try:
        if suffix == '.py':
            doc = ast.get_docstring(ast.parse(p.read_text(encoding='utf-8')))
            return _short(doc) if doc else 'Python module (no docstring)'
        if suffix == '.md':
            for line in p.read_text(encoding='utf-8').splitlines():
                if line.startswith('#'):
                    return _short(line.lstrip('#').strip())
            return 'Markdown document (no heading)'
        if suffix == '.json':
            if p.stat().st_size > 20_000_000:
                return 'JSON file (large; not read)'
            data = json.loads(p.read_text(encoding='utf-8'))
            if isinstance(data, dict):
                bits = [str(data[k]) for k in ('schema_version',) if isinstance(data.get(k), str)]
                for k in ('title', 'purpose', 'description', 'question', 'scope', 'source', 'plan_version'):
                    v = data.get(k)
                    if isinstance(v, str) and v.strip():
                        bits.append(v)
                        break
                return _short(' — '.join(bits)) if bits else 'JSON object'
            return f'JSON list of {len(data)} items'
        if suffix in ('.html', '.htm'):
            text = p.read_text(encoding='utf-8')
            m = (re.search(r'{%\s*block\s+title\s*%}(.*?){%\s*endblock', text, re.S)
                 or re.search(r'<title>(.*?)</title>', text, re.S) or re.search(r'<h1[^>]*>(.*?)</h1>', text, re.S))
            return _short(re.sub(r'<[^>]+>|{[{%].*?[}%]}', '', m.group(1))) if m else 'HTML template'
        if suffix in ('.js', '.css'):
            first = p.read_text(encoding='utf-8').lstrip()
            m = re.match(r'(/\*(.*?)\*/|//(.*))', first, re.S)
            return _short((m.group(2) or m.group(3) or '').strip(' *\n')) if m else f'{suffix[1:].upper()} file'
    except (OSError, UnicodeDecodeError, SyntaxError, ValueError):
        return f'{suffix[1:].upper() or "File"} (could not be read as text)'
    return f'{suffix[1:].upper()} file' if suffix else 'File'


def area_of(path):
    head = path.split('/', 1)[0]
    return head if '/' in path and head in AREAS else ('(root)' if '/' not in path else head)


def build():
    files = tracked_files()
    groups = OrderedDict((a, []) for a in AREAS)
    for f in files:
        groups.setdefault(area_of(f), []).append(f)
    lines = ['# Platform files', '',
             'Every file tracked in the repository, by area, with a one-line description read from the file itself '
             '(docstring, first heading, or schema and title). Generated by `scripts/platform_files_index.py`; '
             'do not edit by hand. The reviewed picture of the platform is [PLATFORM_OVERVIEW.md](PLATFORM_OVERVIEW.md).',
             '', f'**{len(files)} files.**', '', '| Area | Files |', '|---|---|']
    for a, fs in groups.items():
        if fs:
            lines.append(f'| [{a}](#{re.sub(r"[^a-z0-9]+", "-", a.lower()).strip("-")}) — {AREAS.get(a, a)} | {len(fs)} |')
    for a, fs in groups.items():
        if not fs:
            continue
        lines += ['', f'## {a}', '', AREAS.get(a, a) + '.', '', '| File | Description |', '|---|---|']
        for f in fs:
            d = describe(f).replace('|', '\\|')
            lines.append(f'| `{f}` | {d} |')
    return '\n'.join(lines) + '\n'


def main():
    text = build()
    if '--check' in sys.argv:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        sys.exit(0 if current == text else 1)
    OUTPUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
